namespace G502Tool.Core.Model;

/// <summary>
/// Maps PC scan codes (set 1, 0xE0xx = extended) to USB HID keyboard usages. HID usages are
/// positional, so capturing via scan code makes shortcuts correct on AZERTY/QWERTZ layouts too.
/// </summary>
public static class ScanCodes
{
    static readonly Dictionary<int, byte> ScanToHid = Build();
    static readonly Dictionary<byte, int> HidToScan = ScanToHid.GroupBy(kv => kv.Value).ToDictionary(g => g.Key, g => g.First().Key);

    static Dictionary<int, byte> Build()
    {
        var d = new Dictionary<int, byte>();
        int[] letters = { 0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32, 0x31, 0x18, 0x19, 0x10, 0x13, 0x1F, 0x14, 0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C };
        for (int i = 0; i < 26; i++) d[letters[i]] = (byte)(0x04 + i);
        for (int i = 0; i < 9; i++) d[0x02 + i] = (byte)(0x1E + i); // 1..9
        d[0x0B] = 0x27; // 0
        d[0x1C] = 0x28; d[0x01] = 0x29; d[0x0E] = 0x2A; d[0x0F] = 0x2B; d[0x39] = 0x2C;
        d[0x0C] = 0x2D; d[0x0D] = 0x2E; d[0x1A] = 0x2F; d[0x1B] = 0x30; d[0x2B] = 0x31;
        d[0x27] = 0x33; d[0x28] = 0x34; d[0x29] = 0x35; d[0x33] = 0x36; d[0x34] = 0x37; d[0x35] = 0x38;
        d[0x3A] = 0x39;
        for (int i = 0; i < 10; i++) d[0x3B + i] = (byte)(0x3A + i); // F1..F10
        d[0x57] = 0x44; d[0x58] = 0x45; // F11, F12
        d[0xE037] = 0x46; d[0x46] = 0x47; d[0xE11D] = 0x48;
        d[0xE052] = 0x49; d[0xE047] = 0x4A; d[0xE049] = 0x4B; d[0xE053] = 0x4C; d[0xE04F] = 0x4D; d[0xE051] = 0x4E;
        d[0xE04D] = 0x4F; d[0xE04B] = 0x50; d[0xE050] = 0x51; d[0xE048] = 0x52;
        d[0x45] = 0x53; d[0xE035] = 0x54; d[0x37] = 0x55; d[0x4A] = 0x56; d[0x4E] = 0x57; d[0xE01C] = 0x58;
        int[] kp = { 0x4F, 0x50, 0x51, 0x4B, 0x4C, 0x4D, 0x47, 0x48, 0x49 };
        for (int i = 0; i < 9; i++) d[kp[i]] = (byte)(0x59 + i); // keypad 1..9
        d[0x52] = 0x62; d[0x53] = 0x63;
        d[0x56] = 0x64; // ISO key next to left Shift (< > on AZERTY/QWERTZ)
        int[] fHigh = { 0x64, 0x65, 0x66, 0x67, 0x68, 0x69, 0x6A, 0x6B, 0x6C, 0x6D, 0x6E, 0x76 };
        for (int i = 0; i < 12; i++) d[fHigh[i]] = (byte)(0x68 + i); // F13..F24
        d[0xE05D] = 0x65; // Menu
        return d;
    }

    public static byte? ToHid(int scanCode) => ScanToHid.TryGetValue(scanCode, out var u) ? u : null;
    public static int? FromHid(byte usage) => HidToScan.TryGetValue(usage, out var s) ? s : null;
}
